package com.nr.builder;

import com.google.common.collect.Multimap;
import org.gradle.api.GradleException;
import org.reflections.Reflections;
import org.reflections.scanners.TypeAnnotationsScanner;
import org.reflections.serializers.Serializer;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.io.InputStream;
import java.io.StringReader;
import java.io.StringWriter;
import java.util.Properties;

public class PropertySerializer implements Serializer {
    @Override
    public File save(Reflections reflections, String filename) {
        Properties props = new Properties();

        Multimap<String, String> typeAnnotations = reflections.getStore().get(TypeAnnotationsScanner.class.getSimpleName());
        typeAnnotations.keySet().forEach(annotationClass -> {
            String annotatedClasses = String.join(",", typeAnnotations.get(annotationClass));
            props.put(annotationClass, annotatedClasses);
        });

        File file = new File(filename);
        try (FileWriter writer = new FileWriter(file, false)) {
            StringWriter buffer = new StringWriter();
            props.store(buffer, "Automatically generated by " + getClass().getSimpleName());
            writeWithoutTimestamp(buffer.toString(), writer);
        } catch (Throwable t) {
            throw new GradleException("Failed to write " + filename, t);
        }

        return file;
    }

    /**
     * Properties.store() always writes the current time as a comment on the line after the header comment.
     * Drop it so identical inputs produce identical output.
     */
    private static void writeWithoutTimestamp(String stored, FileWriter writer) throws IOException {
        BufferedReader reader = new BufferedReader(new StringReader(stored));
        String line;
        int lineNumber = 0;
        while ((line = reader.readLine()) != null) {
            if (++lineNumber != 2 || !line.startsWith("#")) {
                writer.write(line);
                writer.write(System.lineSeparator());
            }
        }
    }

    @Override
    public Reflections read(InputStream inputStream) {
        throw new GradleException("We don't read using this serializer");
    }

    @Override
    public String toString(Reflections reflections) {
        throw new GradleException("Use save() and not toString()");
    }
}
