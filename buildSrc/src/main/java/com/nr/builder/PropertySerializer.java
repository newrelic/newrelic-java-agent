package com.nr.builder;

import com.google.common.collect.Multimap;
import org.gradle.api.GradleException;
import org.reflections.Reflections;
import org.reflections.scanners.TypeAnnotationsScanner;
import org.reflections.serializers.Serializer;

import java.io.File;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Pattern;

public class PropertySerializer implements Serializer {
    // Annotation and class names never need properties-file escaping. Anything else fails the build instead of
    // being written in a form the reader would parse differently.
    private static final Pattern SAFE_NAME = Pattern.compile("[A-Za-z0-9_.$]+");

    /**
     * Writes one {@code annotation=ClassA,ClassB} line per annotation. Annotations and classes are sorted, and the
     * file uses '\n' and UTF-8, so the output depends only on the classes found and not on the order they were
     * scanned in, the JDK, or the platform. There is no timestamp comment.
     */
    @Override
    public File save(Reflections reflections, String filename) {
        Multimap<String, String> typeAnnotations = reflections.getStore().get(TypeAnnotationsScanner.class.getSimpleName());

        StringBuilder content = new StringBuilder("#Automatically generated by " + getClass().getSimpleName() + "\n");
        for (String annotationClass : new TreeSet<>(typeAnnotations.keySet())) {
            checkSafe(annotationClass);
            Set<String> annotatedClasses = new TreeSet<>(typeAnnotations.get(annotationClass));
            annotatedClasses.forEach(PropertySerializer::checkSafe);
            content.append(annotationClass).append('=').append(String.join(",", annotatedClasses)).append('\n');
        }

        File file = new File(filename);
        try {
            Files.write(file.toPath(), content.toString().getBytes(StandardCharsets.UTF_8));
        } catch (Throwable t) {
            throw new GradleException("Failed to write " + filename, t);
        }

        return file;
    }

    private static void checkSafe(String name) {
        if (!SAFE_NAME.matcher(name).matches()) {
            throw new GradleException("Cannot write '" + name + "' to the pointcut properties file because it contains characters "
                    + "other than letters, digits, '_', '.' and '$'. Rename the class or extend PropertySerializer to escape it.");
        }
    }

    @Override
    public Reflections read(InputStream inputStream) {
        throw new GradleException("We don't read using this serializer");
    }

    @Override
    public String toString(Reflections reflections) {
        throw new GradleException("Use save() and not toString()");
    }
}
