package com.nr.builder;

import com.google.common.collect.Multimap;
import org.gradle.api.GradleException;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;
import org.reflections.Reflections;
import org.reflections.scanners.TypeAnnotationsScanner;
import org.reflections.util.ConfigurationBuilder;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

public class PropertySerializerTest {
    @Rule
    public TemporaryFolder temporaryFolder = new TemporaryFolder();

    private static Reflections reflectionsWith(String... annotationAndClassPairs) {
        Reflections reflections = new Reflections(new ConfigurationBuilder().setScanners(new TypeAnnotationsScanner()));
        Multimap<String, String> store = reflections.getStore().getOrCreate(TypeAnnotationsScanner.class.getSimpleName());
        for (int i = 0; i < annotationAndClassPairs.length; i += 2) {
            store.put(annotationAndClassPairs[i], annotationAndClassPairs[i + 1]);
        }
        return reflections;
    }

    private String serialize(Reflections reflections) throws Exception {
        File file = new File(temporaryFolder.getRoot(), "PointcutClasses.properties");
        new PropertySerializer().save(reflections, file.getAbsolutePath());
        return new String(Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8);
    }

    @Test
    public void save_sortsAnnotationsAndClassesAndUsesLineFeeds() throws Exception {
        // Inserted in an arbitrary order, as a scan of the file system would produce them.
        Reflections reflections = reflectionsWith(
                "b.Annotation", "pkg.Zebra",
                "a.Annotation", "pkg.Mango",
                "b.Annotation", "pkg.Apple",
                "a.Annotation", "pkg.Banana$Inner");

        assertEquals("#Automatically generated by PropertySerializer\n"
                + "a.Annotation=pkg.Banana$Inner,pkg.Mango\n"
                + "b.Annotation=pkg.Apple,pkg.Zebra\n", serialize(reflections));
    }

    @Test
    public void save_sameContentInADifferentOrderGivesIdenticalOutput() throws Exception {
        String first = serialize(reflectionsWith("a.A", "x.One", "a.A", "x.Two", "b.B", "x.Three"));
        String second = serialize(reflectionsWith("b.B", "x.Three", "a.A", "x.Two", "a.A", "x.One"));
        assertEquals(first, second);
    }

    @Test
    public void save_hasNoTimestampOrOtherCommentLine() throws Exception {
        String content = serialize(reflectionsWith("a.A", "x.One"));
        for (String line : content.split("\n")) {
            assertTrue(line, !line.startsWith("#") || line.equals("#Automatically generated by PropertySerializer"));
        }
        assertFalse(content.contains("\r"));
    }

    @Test
    public void save_withNothingFoundWritesOnlyTheHeader() throws Exception {
        assertEquals("#Automatically generated by PropertySerializer\n", serialize(reflectionsWith()));
    }

    @Test
    public void save_rejectsNamesThatWouldNeedEscaping() throws Exception {
        for (String[] pair : new String[][] {{"a.A", "x.Bad Name"}, {"a.A", "x.Bad=Name"}, {"a.A", "x.Bad,Name"}, {"a A", "x.One"}, {"a.A", "x.Bad#"}, {"a.A", ""}}) {
            try {
                serialize(reflectionsWith(pair));
                fail("Expected a GradleException for " + pair[0] + " / " + pair[1]);
            } catch (GradleException e) {
                assertTrue(e.getMessage(), e.getMessage().contains("Cannot write"));
            }
        }
    }
}
